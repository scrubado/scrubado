"use strict";

// src/routes/payments.js
// Development-only Stripe PaymentIntent preparation. No card is charged here.
// A Stripe webhook, not this endpoint, must establish payment success.

const express = require("express");
const Stripe = require("stripe");
const pool = require("../db");
const { authenticateCustomer } = require("../middleware/authenticate");

const router = express.Router();
const uuidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

router.post("/create-intent", authenticateCustomer, async (req, res) => {
  // Until verified webhooks, capture rules, and checkout UI are implemented,
  // never expose this route in production or without an explicit dev flag.
  if (process.env.NODE_ENV === "production" ||
      process.env.ENABLE_DEV_PAYMENT_INTENTS !== "true") {
    return res.status(503).json({ error: "Payments are not enabled" });
  }

  const key = process.env.STRIPE_SECRET_KEY;
  if (!key || !key.startsWith("sk_test_")) {
    return res.status(503).json({ error: "Stripe test mode is not configured" });
  }

  const bookingId = req.body && req.body.booking_id;
  if (typeof bookingId !== "string" || !uuidPattern.test(bookingId)) {
    return res.status(400).json({ error: "Valid booking_id required" });
  }

  const stripe = new Stripe(key, { timeout: 12000, maxNetworkRetries: 1 });
  let client;
  let inTransaction = false;

  try {
    client = await pool.connect();
    await client.query("BEGIN");
    inTransaction = true;

    // Locks the booking so competing requests serialize for this booking.
    // The DB's unique payments.booking_id constraint is an extra safeguard.
    const result = await client.query(`
      SELECT b.id, b.customer_id, b.status, b.quote_id,
             b.quoted_price_cents, b.required_crew_size,
             q.customer_id AS quote_user_id,
             q.customer_total_cents, q.currency, q.status AS quote_status,
             (SELECT COUNT(*)::integer FROM public.booking_cleaners bc
               WHERE bc.booking_id = b.id AND bc.assignment_status = 'assigned') AS crew_count,
             (SELECT COUNT(*)::integer FROM public.booking_cleaners bc
               WHERE bc.booking_id = b.id AND bc.assignment_status = 'assigned'
                 AND bc.crew_role = 'lead') AS leads,
             (SELECT COUNT(*)::integer FROM public.booking_cleaners bc
               WHERE bc.booking_id = b.id AND bc.assignment_status = 'assigned'
                 AND bc.crew_role = 'second') AS seconds
      FROM public.bookings b
      JOIN public.quotes q ON q.id = b.quote_id
      WHERE b.id = $1
      FOR UPDATE OF b
    `, [bookingId]);

    const booking = result.rows[0];
    if (!booking || booking.customer_id !== req.customer.customer_profile_id ||
        booking.quote_user_id !== req.customer.id) {
      await client.query("ROLLBACK"); inTransaction = false;
      return res.status(404).json({ error: "Booking not found" });
    }

    const amount = Number(booking.quoted_price_cents);
    if (booking.status !== "accepted" || booking.quote_status !== "used" ||
        !booking.quote_id || !Number.isSafeInteger(amount) || amount < 50 ||
        String(booking.quoted_price_cents) !== String(booking.customer_total_cents) ||
        String(booking.currency).trim().toLowerCase() !== "usd" ||
        (booking.required_crew_size !== 1 && booking.required_crew_size !== 2) ||
        booking.crew_count !== booking.required_crew_size || booking.leads !== 1 ||
        booking.seconds !== (booking.required_crew_size === 2 ? 1 : 0)) {
      await client.query("ROLLBACK"); inTransaction = false;
      return res.status(409).json({ error: "Booking is not eligible for payment" });
    }

    // Insert once, with a stable UUID idempotency key generated by Neon.
    // The row stays pending until Stripe returns an intent.
    const paymentResult = await client.query(`
      INSERT INTO public.payments
        (booking_id, customer_id, amount_cents, currency, status)
      VALUES ($1, $2, $3, 'usd', 'pending')
      ON CONFLICT (booking_id) DO NOTHING
      RETURNING *
    `, [bookingId, req.customer.customer_profile_id, amount]);

    let payment = paymentResult.rows[0];
    if (!payment) {
      const prior = await client.query(
        "SELECT * FROM public.payments WHERE booking_id = $1 FOR UPDATE",
        [bookingId]
      );
      payment = prior.rows[0];
    }
    if (!payment || payment.customer_id !== req.customer.customer_profile_id ||
        Number(payment.amount_cents) !== amount || payment.currency !== "usd") {
      await client.query("ROLLBACK"); inTransaction = false;
      return res.status(409).json({ error: "Existing payment record does not match booking" });
    }
    if (["succeeded", "requires_capture", "processing", "cancelled", "failed"].includes(payment.status)) {
      await client.query("ROLLBACK"); inTransaction = false;
      return res.status(409).json({ error: "Payment requires reconciliation before retry" });
    }

    let intent;
    if (payment.stripe_payment_intent_id) {
      intent = await stripe.paymentIntents.retrieve(payment.stripe_payment_intent_id);
    } else {
      // Stable idempotency key prevents extra intents after network retries/crashes.
      intent = await stripe.paymentIntents.create({
        amount,
        currency: "usd",
        capture_method: "manual",
        automatic_payment_methods: { enabled: true, allow_redirects: "never" },
        metadata: {
          booking_id: bookingId,
          payment_id: payment.id
        }
      }, { idempotencyKey: `scrubado-payment-${payment.idempotency_key}` });
    }

    if (intent.livemode || intent.amount !== amount || intent.currency !== "usd" ||
        intent.metadata.booking_id !== bookingId || intent.metadata.payment_id !== payment.id) {
      throw new Error("Stripe PaymentIntent does not match the booking");
    }
    if (!["requires_payment_method", "requires_confirmation", "requires_action"].includes(intent.status)) {
      await client.query("ROLLBACK"); inTransaction = false;
      return res.status(409).json({ error: "Stripe payment state requires reconciliation" });
    }

    await client.query(`
      UPDATE public.payments
      SET stripe_payment_intent_id = $1,
          status = $2,
          updated_at = NOW()
      WHERE id = $3
    `, [intent.id, intent.status === "requires_confirmation" ? "pending" : intent.status, payment.id]);

    await client.query("COMMIT"); inTransaction = false;
    return res.status(200).json({
      status: "ready_for_test_checkout",
      booking_id: bookingId,
      amount_cents: amount,
      currency: "usd",
      payment_intent_id: intent.id,
      client_secret: intent.client_secret,
      capture_method: "manual",
      note: "Test mode only. No card has been authorized or charged. Payment confirmation requires a signed webhook."
    });
  } catch (error) {
    if (client && inTransaction) {
      try { await client.query("ROLLBACK"); } catch (rollbackError) {
        console.error("Payment rollback failed:", rollbackError.message);
      }
    }
    console.error("PaymentIntent preparation failed:", error.type || error.code || error.message);
    return res.status(503).json({ error: "Unable to prepare payment; retry later" });
  } finally {
    if (client) client.release();
  }
});

module.exports = router;